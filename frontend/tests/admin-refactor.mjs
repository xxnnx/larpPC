import assert from 'node:assert/strict';
import { createServer } from 'vite';

// Use a locally installed Playwright, or provide its module URL explicitly.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = await createServer({ server: { host: '127.0.0.1', port: 5176, strictPort: true } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage();
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('token', `x.${btoa(JSON.stringify({ exp: Date.now() / 1000 + 3600 }))}.x`));
  const rooms = [{ id: 1, name: 'Standard' }];
  const computers = [{ id: 10, number: 1, name: 'PC 1', roomId: 1, status: 'AVAILABLE' }];
  const tariffs = [{ id: 20, name: 'Часовой', roomId: 1, tariffType: 'HOURLY', price: 100, active: true }];
  const bookings = [{ id: 30, computerId: 10, tariffName: 'Часовой', status: 'ACTIVE', startTime: '2030-01-01T12:00:00', endTime: '2030-01-01T13:00:00', priceAtBooking: 100 }];
  const writes = [];
  let computerReads = 0;
  let failWrite = false;
  let failRead = false;
  await page.route('**/api/**', async route => {
    const req = route.request();
    const path = new URL(req.url()).pathname;
    if (!path.startsWith('/api/')) return route.continue();
    let data;
    if (req.method() !== 'GET') {
      const body = req.postDataJSON();
      writes.push({ path, method: req.method(), body });
      if (failWrite) return route.fulfill({ status: 400, json: { error: 'Проверочная ошибка' } });
      if (path === '/api/tariffs/20') Object.assign(tariffs[0], body);
      if (path.endsWith('/deactivate')) tariffs[0].active = false;
      if (path.endsWith('/activate')) tariffs[0].active = true;
      if (path === '/api/tariffs') tariffs.push({ ...body, id: 21, active: true });
      if (path === '/api/computers/10') Object.assign(computers[0], body);
      if (path === '/api/bookings/30/cancel') bookings[0].status = 'CANCELLED';
      data = path === '/api/bookings' ? { ...body, id: 31, tariffName: 'Часовой', priceAtBooking: 225 } : {};
    } else if (path === '/api/auth/me') data = { id: 1, name: 'Admin', role: 'ADMIN' };
    else if (path === '/api/rooms') data = rooms;
    else if (path === '/api/rooms/1/computers') { computerReads++; data = computers; }
    else if (path === '/api/tariffs' || path === '/api/tariffs/room/1') {
      if (failRead) return route.fulfill({ status: 500, json: { error: 'Ошибка загрузки' } });
      data = tariffs;
    } else if (path === '/api/bookings') data = bookings;
    else throw new Error(`Unexpected request: ${path}`);
    await route.fulfill({ json: data });
  });
  const button = name => page.getByRole('button', { name, exact: true });
  const field = name => page.getByRole('textbox', { name, exact: true });
  const visibleSection = () => page.locator('section:visible');
  await page.goto('http://127.0.0.1:5176/admin');
  await page.getByRole('heading', { name: 'Бронь #30 · PC 1' }).waitFor();
  const reads = computerReads;
  await button('Тарифы').click();
  await page.getByRole('heading', { name: 'Часовой', exact: true }).waitFor();
  assert.equal(computerReads, reads, 'Tariffs must not load computers');
  await button('Редактировать').click();
  await field('Название').fill('Новая цена');
  await page.getByRole('spinbutton', { name: 'Цена за час, ₽' }).fill('150');
  await button('Компьютеры').click();
  await page.getByRole('heading', { name: '№1 · PC 1' }).waitFor();
  await button('Тарифы').click();
  await field('Название').waitFor();
  assert.equal(await field('Название').inputValue(), 'Новая цена');
  failWrite = true;
  await button('Сохранить тариф').click();
  await page.getByRole('alert').filter({ hasText: 'Проверочная ошибка' }).waitFor();
  assert.equal(await field('Название').inputValue(), 'Новая цена');
  failWrite = false;
  await button('Сохранить тариф').click();
  await page.getByRole('heading', { name: 'Новая цена', exact: true }).waitFor();
  assert.deepEqual(writes.at(-1), { path: '/api/tariffs/20', method: 'PATCH', body: { name: 'Новая цена', price: 150 } });
  await button('Отключить').click();
  await button('Да, отключить').click();
  await button('Включить').waitFor();
  await button('Включить').click();
  await button('Отключить').waitFor();
  await field('Название').fill('90 минут');
  await visibleSection().getByLabel('Зал', { exact: true }).selectOption('1');
  await page.getByLabel('Тип', { exact: true }).selectOption('PACKAGE');
  await page.getByRole('spinbutton', { name: 'Цена пакета, ₽' }).fill('200');
  await page.getByRole('spinbutton', { name: 'Длительность, минут' }).fill('90');
  await button('Добавить тариф').click();
  await page.getByRole('heading', { name: '90 минут', exact: true }).waitFor();
  assert.equal(writes.at(-1).body.durationMinutes, 90);
  failRead = true;
  await button('Обновить список').click();
  await page.getByRole('alert').filter({ hasText: 'Ошибка загрузки' }).waitFor();
  failRead = false;
  await button('Обновить список').click();
  await visibleSection().getByRole('heading', { name: '90 минут', exact: true }).waitFor();
  await button('Компьютеры').click();
  await button('Редактировать').click();
  await field('Название').fill('PC updated');
  await button('Сохранить компьютер').click();
  await page.getByRole('heading', { name: '№1 · PC updated' }).waitFor();
  assert.equal(writes.at(-1).body.number, 1);
  await button('Бронирования').click();
  await button('Отменить бронь').click();
  await button('Да, отменить').click();
  await visibleSection().getByRole('article').getByText('Отменена', { exact: true }).waitFor();
  assert.equal(writes.at(-1).path, '/api/bookings/30/cancel');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.goto('http://127.0.0.1:5176/booking?room=1');
  await button('Standard').click();
  await button('PC updated').click();
  await page.getByRole('button', { name: /Новая цена/ }).click();
  await page.getByLabel('Начало сеанса (московское время)').fill('2030-01-01T12:00');
  await page.getByRole('combobox', { name: /^Минуты/ }).selectOption('30');
  await button('ЗАБРОНИРОВАТЬ').click();
  await page.getByRole('heading', { name: 'Бронь №31 создана' }).waitFor();
  assert.deepEqual(writes.at(-1).body, { computerId: 10, tariffId: 20, startTime: '2030-01-01T12:00:00', endTime: '2030-01-01T13:30:00' });
  await button('Новая бронь').click();
  await page.getByRole('button', { name: /90 минут/ }).click();
  await page.getByLabel('Начало сеанса (московское время)').fill('2030-01-02T12:00');
  await button('ЗАБРОНИРОВАТЬ').click();
  await page.getByRole('heading', { name: 'Бронь №31 создана' }).waitFor();
  assert.equal(writes.at(-1).body.endTime, '2030-01-02T13:30:00');
  assert.equal(writes.at(-1).body.tariffId, 21);
  assert.deepEqual(errors, []);
  console.log('PASS: admin navigation, drafts, errors/retry, tariff edit/status/package, computer edit, booking cancel, mobile layout');
} finally {
  await browser?.close();
  await server.close();
}

